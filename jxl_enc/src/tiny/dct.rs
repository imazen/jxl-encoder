/// sqrt(2) constant used in DCT
pub const SQRT2: f32 = 1.41421356237;

/// Multipliers for DCT computation.
/// Generated by: `1.0 / (2 * cos((i + 0.5) * pi / N))` for i in 0..N/2
// Copied directly from libjxl-tiny dct_scales.h
pub const WC_MULTIPLIERS_4: [f32; 2] = [0.541196100146197, 1.3065629648763764];

// Copied directly from libjxl-tiny dct_scales.h
pub const WC_MULTIPLIERS_8: [f32; 4] = [
    0.5097955791041592,
    0.6013448869350453,
    0.8999762231364156,
    2.5629154477415055,
];

// Copied directly from libjxl-tiny dct_scales.h
pub const WC_MULTIPLIERS_16: [f32; 8] = [
    0.5024192861881557,
    0.5224986149396889,
    0.5669440348163577,
    0.6468217833599901,
    0.7881546234512502,
    1.060677685990347,
    1.7224470982383342,
    5.101148618689155,
];

/// Resample scales for DC extraction from larger DCTs.
// Copied directly from libjxl-tiny dct_scales.h
pub const DCT_RESAMPLE_SCALE_16_TO_2: [f32; 2] = [1.000000000000000000, 0.901764195028874394];

pub const DCT_RESAMPLE_SCALE_2_TO_16: [f32; 2] = [1.000000000000000000, 1.108937353592731823];

// =============================================================================
// DCT Algorithm Implementation
// =============================================================================

/// In-place 1D DCT for N=2
#[inline]
fn dct1d_2(mem: &mut [f32]) {
    let in1 = mem[0];
    let in2 = mem[1];
    mem[0] = in1 + in2;
    mem[1] = in1 - in2;
}

/// In-place 1D DCT for N=4
fn dct1d_4(mem: &mut [f32]) {
    // AddReverse: tmp[i] = mem[i] + mem[N-1-i] for first half
    // SubReverse: tmp[N/2+i] = mem[i] - mem[N-1-i] for second half
    let mut tmp = [0.0f32; 4];
    tmp[0] = mem[0] + mem[3];
    tmp[1] = mem[1] + mem[2];
    tmp[2] = mem[0] - mem[3];
    tmp[3] = mem[1] - mem[2];

    // DCT on first half
    dct1d_2(&mut tmp[0..2]);

    // Multiply second half by WcMultipliers
    tmp[2] *= WC_MULTIPLIERS_4[0];
    tmp[3] *= WC_MULTIPLIERS_4[1];

    // DCT on second half
    dct1d_2(&mut tmp[2..4]);

    // B transform on second half
    // B: tmp[0] = sqrt2 * tmp[0] + tmp[1], then tmp[i] = tmp[i] + tmp[i+1] for rest
    tmp[2] = SQRT2 * tmp[2] + tmp[3];
    // (no more elements for N/2=2)

    // InverseEvenOdd: interleave even and odd
    mem[0] = tmp[0];
    mem[2] = tmp[1];
    mem[1] = tmp[2];
    mem[3] = tmp[3];
}

/// In-place 1D DCT for N=8
fn dct1d_8(mem: &mut [f32]) {
    let mut tmp = [0.0f32; 8];

    // AddReverse for first half
    for i in 0..4 {
        tmp[i] = mem[i] + mem[7 - i];
    }
    // SubReverse for second half
    for i in 0..4 {
        tmp[4 + i] = mem[i] - mem[7 - i];
    }

    // DCT on first half
    dct1d_4(&mut tmp[0..4]);

    // Multiply second half by WcMultipliers
    for i in 0..4 {
        tmp[4 + i] *= WC_MULTIPLIERS_8[i];
    }

    // DCT on second half
    dct1d_4(&mut tmp[4..8]);

    // B transform on second half
    tmp[4] = SQRT2 * tmp[4] + tmp[5];
    tmp[5] += tmp[6];
    tmp[6] += tmp[7];

    // InverseEvenOdd: interleave
    for i in 0..4 {
        mem[2 * i] = tmp[i];
        mem[2 * i + 1] = tmp[4 + i];
    }
}

/// In-place 1D DCT for N=16
fn dct1d_16(mem: &mut [f32]) {
    let mut tmp = [0.0f32; 16];

    // AddReverse for first half
    for i in 0..8 {
        tmp[i] = mem[i] + mem[15 - i];
    }
    // SubReverse for second half
    for i in 0..8 {
        tmp[8 + i] = mem[i] - mem[15 - i];
    }

    // DCT on first half
    dct1d_8(&mut tmp[0..8]);

    // Multiply second half by WcMultipliers
    for i in 0..8 {
        tmp[8 + i] *= WC_MULTIPLIERS_16[i];
    }

    // DCT on second half
    dct1d_8(&mut tmp[8..16]);

    // B transform on second half
    tmp[8] = SQRT2 * tmp[8] + tmp[9];
    for i in 1..7 {
        tmp[8 + i] += tmp[8 + i + 1];
    }

    // InverseEvenOdd: interleave
    for i in 0..8 {
        mem[2 * i] = tmp[i];
        mem[2 * i + 1] = tmp[8 + i];
    }
}

/// Transpose an NxM block in-place (actually copies to output).
fn transpose<const N: usize, const M: usize>(input: &[f32], output: &mut [f32]) {
    for row in 0..N {
        for col in 0..M {
            output[col * N + row] = input[row * M + col];
        }
    }
}

/// Compute scaled 8x8 DCT.
///
/// Input: 8x8 block in row-major order
/// Output: 8x8 DCT coefficients in **transposed** layout
///
/// IMPORTANT: libjxl-tiny's ComputeScaledDCT does NOT transpose back for square blocks.
/// The decoder expects coefficients in this transposed layout. For 8x8 blocks,
/// output[cx * 8 + cy] contains the coefficient for frequency (cy, cx) where
/// cy is the vertical frequency and cx is the horizontal frequency.
pub fn dct_8x8(input: &[f32; 64], output: &mut [f32; 64]) {
    let mut tmp = [0.0f32; 64];

    // Transform rows
    for row in 0..8 {
        let row_start = row * 8;
        tmp[row_start..row_start + 8].copy_from_slice(&input[row_start..row_start + 8]);
        dct1d_8(&mut tmp[row_start..row_start + 8]);
        // Scale by 1/N
        for i in 0..8 {
            tmp[row_start + i] *= 1.0 / 8.0;
        }
    }

    // Transpose
    let mut transposed = [0.0f32; 64];
    transpose::<8, 8>(&tmp, &mut transposed);

    // Transform columns (now rows after transpose)
    for row in 0..8 {
        let row_start = row * 8;
        dct1d_8(&mut transposed[row_start..row_start + 8]);
        // Scale by 1/N
        for i in 0..8 {
            transposed[row_start + i] *= 1.0 / 8.0;
        }
    }

    // DO NOT transpose back! libjxl-tiny expects transposed output for square blocks.
    // This matches ComputeScaledDCT in libjxl-tiny/encoder/enc_transforms-inl.h
    output.copy_from_slice(&transposed);
}

/// Compute scaled 16x8 DCT (16 rows, 8 columns).
///
/// Input: 16x8 block in row-major order (128 floats)
/// Output: 16x8 DCT coefficients
pub fn dct_16x8(input: &[f32; 128], output: &mut [f32; 128]) {
    let mut tmp = [0.0f32; 128];

    // Transform rows (8 columns each)
    for row in 0..16 {
        let row_start = row * 8;
        tmp[row_start..row_start + 8].copy_from_slice(&input[row_start..row_start + 8]);
        dct1d_8(&mut tmp[row_start..row_start + 8]);
        for i in 0..8 {
            tmp[row_start + i] *= 1.0 / 8.0;
        }
    }

    // Transpose 16x8 -> 8x16
    let mut transposed = [0.0f32; 128];
    for row in 0..16 {
        for col in 0..8 {
            transposed[col * 16 + row] = tmp[row * 8 + col];
        }
    }

    // Transform columns (now 16 elements each)
    for row in 0..8 {
        let row_start = row * 16;
        dct1d_16(&mut transposed[row_start..row_start + 16]);
        for i in 0..16 {
            transposed[row_start + i] *= 1.0 / 16.0;
        }
    }

    // No final transpose — C++ ComputeScaledDCT<16,8> (ROWS >= COLS branch)
    // does not include a final transpose, matching DCT8x8 behavior.
    // Output is in 8x16 layout: output[fx * 16 + fy] for frequency (fy, fx).
    output.copy_from_slice(&transposed);
}

/// Compute scaled 8x16 DCT (8 rows, 16 columns).
///
/// Input: 8x16 block in row-major order (128 floats)
/// Output: 8x16 DCT coefficients
pub fn dct_8x16(input: &[f32; 128], output: &mut [f32; 128]) {
    let mut tmp = [0.0f32; 128];

    // Transform rows (16 columns each)
    for row in 0..8 {
        let row_start = row * 16;
        tmp[row_start..row_start + 16].copy_from_slice(&input[row_start..row_start + 16]);
        dct1d_16(&mut tmp[row_start..row_start + 16]);
        for i in 0..16 {
            tmp[row_start + i] *= 1.0 / 16.0;
        }
    }

    // Transpose 8x16 -> 16x8
    let mut transposed = [0.0f32; 128];
    for row in 0..8 {
        for col in 0..16 {
            transposed[col * 8 + row] = tmp[row * 16 + col];
        }
    }

    // Transform columns (now 8 elements each)
    for row in 0..16 {
        let row_start = row * 8;
        dct1d_8(&mut transposed[row_start..row_start + 8]);
        for i in 0..8 {
            transposed[row_start + i] *= 1.0 / 8.0;
        }
    }

    // Transpose 16x8 -> 8x16
    for row in 0..16 {
        for col in 0..8 {
            output[col * 16 + row] = transposed[row * 8 + col];
        }
    }
}

/// Compute scaled 16x16 DCT (16 rows, 16 columns).
///
/// Input: 16x16 block in row-major order (256 floats)
/// Output: 16x16 DCT coefficients
///
/// Like `dct_8x8()`, there is NO final transpose for square blocks.
/// C++ `ComputeScaledDCT<16,16>` takes the ROWS >= COLS branch (no final transpose).
pub fn dct_16x16(input: &[f32; 256], output: &mut [f32; 256]) {
    let mut tmp = [0.0f32; 256];

    // Transform rows (16 columns each)
    for row in 0..16 {
        let row_start = row * 16;
        tmp[row_start..row_start + 16].copy_from_slice(&input[row_start..row_start + 16]);
        dct1d_16(&mut tmp[row_start..row_start + 16]);
        // Scale by 1/N
        for i in 0..16 {
            tmp[row_start + i] *= 1.0 / 16.0;
        }
    }

    // Transpose 16x16
    let mut transposed = [0.0f32; 256];
    transpose::<16, 16>(&tmp, &mut transposed);

    // Transform columns (now rows after transpose)
    for row in 0..16 {
        let row_start = row * 16;
        dct1d_16(&mut transposed[row_start..row_start + 16]);
        // Scale by 1/N
        for i in 0..16 {
            transposed[row_start + i] *= 1.0 / 16.0;
        }
    }

    // DO NOT transpose back! Same as DCT8x8 - square blocks stay transposed.
    output.copy_from_slice(&transposed);
}

/// Extract DC values from 16x16 DCT coefficients.
/// Returns 4 DC values (for the 4 covered 8x8 blocks) in order [dc00, dc01, dc10, dc11].
///
/// The LLF region is 2x2 coefficients at positions [0, 1, 16, 17] in the 16x16 layout
/// (stride 16). We apply `DCTTotalResampleScale<16, 2>` to each dimension, then a
/// 2x2 IDCT to get the 4 DC values.
///
/// C++ uses `ReinterpretingIDCT<16, 16, 2, 2, 2, 2>` with the ROWS >= COLS branch
/// (since ROWS=COLS=2), which reads LLF in (y, x) = (0..LF_COLS, 0..LF_ROWS) order.
pub fn dc_from_dct_16x16(coeffs: &[f32; 256]) -> [f32; 4] {
    let s0 = DCT_RESAMPLE_SCALE_16_TO_2[0]; // 1.0
    let s1 = DCT_RESAMPLE_SCALE_16_TO_2[1]; // 0.9018...

    // Read LLF 2x2 from positions [0, 1, 16, 17] and apply resample scales.
    // C++ ROWS >= COLS branch: block[y * ROWS + x] = input[y * stride + x] * scale_col[y] * scale_row[x]
    // For 16x16 (ROWS=COLS=2): scale_col = scale_row = DCTTotalResampleScale<16,2>
    let b00 = coeffs[0] * s0 * s0;
    let b10 = coeffs[1] * s1 * s0; // block[0*2+1]  = input[0*16+1] * s0 * s1 -- but C++ has [y*R+x] = [y*stride+x]*s_c(y)*s_r(x)
    let b01 = coeffs[16] * s0 * s1; // block[1*2+0] = input[1*16+0] * s1 * s0
    let b11 = coeffs[17] * s1 * s1;

    // 2x2 IDCT (ComputeScaledIDCT<2,2>):
    // For 2-point IDCT: [a, b] -> [a+b, a-b]
    // Apply to rows then columns:
    // Row 0: [b00+b10, b00-b10]
    // Row 1: [b01+b11, b01-b11]
    // Column 0: [(b00+b10)+(b01+b11), (b00+b10)-(b01+b11)]
    // Column 1: [(b00-b10)+(b01-b11), (b00-b10)-(b01-b11)]
    let dc00 = (b00 + b10) + (b01 + b11);
    let dc01 = (b00 - b10) + (b01 - b11);
    let dc10 = (b00 + b10) - (b01 + b11);
    let dc11 = (b00 - b10) - (b01 - b11);

    [dc00, dc01, dc10, dc11]
}

/// Extract DC value from 8x8 DCT coefficients.
/// For DCT8, DC is just the [0,0] coefficient.
#[inline]
pub fn dc_from_dct_8x8(coeffs: &[f32; 64]) -> f32 {
    coeffs[0]
}

/// Extract DC values from 16x8 DCT coefficients.
/// Returns 2 DC values (for the 2 covered 8x8 blocks).
///
/// Uses ReinterpretingIDCT to convert LF coefficients to DC.
pub fn dc_from_dct_16x8(coeffs: &[f32; 128]) -> [f32; 2] {
    // For 16x8, the LF region is 2x1 coefficients (2 rows, 1 col in freq domain)
    // In the 8×16 output layout (stride 16), both LLF coefficients are at indices 0 and 1.
    //
    // C++ DCFromLowestFrequencies uses DCTTotalResampleScale<16, 2> (forward direction:
    // FROM 16-point DCT TO 2-point domain). Must use 16_TO_2 scales, NOT 2_TO_16.
    let lf0 = coeffs[0] * DCT_RESAMPLE_SCALE_16_TO_2[0];
    let lf1 = coeffs[1] * DCT_RESAMPLE_SCALE_16_TO_2[1];

    // 2-point IDCT: [a+b, a-b]
    [lf0 + lf1, lf0 - lf1]
}

/// Extract DC values from 8x16 DCT coefficients.
/// Returns 2 DC values (for the 2 covered 8x8 blocks).
pub fn dc_from_dct_8x16(coeffs: &[f32; 128]) -> [f32; 2] {
    // For 8x16, the LF region is 1x2 coefficients
    // Uses 16_TO_2 direction (FROM 16-point DCT TO 2-point domain).
    let lf0 = coeffs[0] * DCT_RESAMPLE_SCALE_16_TO_2[0];
    let lf1 = coeffs[1] * DCT_RESAMPLE_SCALE_16_TO_2[1];

    // 2-point IDCT: [a+b, a-b]
    [lf0 + lf1, lf0 - lf1]
}

