/// Resample scales for DC extraction from 32-point DCT to 4-point domain.
/// DCTTotalResampleScale<32, 4> from libjxl.
pub const DCT_RESAMPLE_SCALE_32_TO_4: [f32; 4] = [
    1.0,
    0.974886821136879522,
    0.901764195028874394,
    0.787054918159101335,
];

/// In-place 1D DCT for N=32
fn dct1d_32(mem: &mut [f32]) {
    let mut tmp = [0.0f32; 32];

    // AddReverse for first half
    for i in 0..16 {
        tmp[i] = mem[i] + mem[31 - i];
    }
    // SubReverse for second half
    for i in 0..16 {
        tmp[16 + i] = mem[i] - mem[31 - i];
    }

    // DCT on first half
    dct1d_16(&mut tmp[0..16]);

    // Multiply second half by WcMultipliers
    for i in 0..16 {
        tmp[16 + i] *= WC_MULTIPLIERS_32[i];
    }

    // DCT on second half
    dct1d_16(&mut tmp[16..32]);

    // B transform on second half
    tmp[16] = SQRT2 * tmp[16] + tmp[17];
    for i in 1..15 {
        tmp[16 + i] += tmp[16 + i + 1];
    }

    // InverseEvenOdd: interleave
    for i in 0..16 {
        mem[2 * i] = tmp[i];
        mem[2 * i + 1] = tmp[16 + i];
    }
}

/// Compute scaled 32x32 DCT (32 rows, 32 columns).
///
/// Input: 32x32 block in row-major order (1024 floats)
/// Output: 32x32 DCT coefficients
///
/// Like `dct_8x8()` and `dct_16x16()`, there is NO final transpose for square blocks.
/// C++ `ComputeScaledDCT<32,32>` takes the ROWS >= COLS branch (no final transpose).
pub fn dct_32x32(input: &[f32; 1024], output: &mut [f32; 1024]) {
    let mut tmp = [0.0f32; 1024];

    // Transform rows (32 columns each)
    for row in 0..32 {
        let row_start = row * 32;
        tmp[row_start..row_start + 32].copy_from_slice(&input[row_start..row_start + 32]);
        dct1d_32(&mut tmp[row_start..row_start + 32]);
        // Scale by 1/N
        for i in 0..32 {
            tmp[row_start + i] *= 1.0 / 32.0;
        }
    }

    // Transpose 32x32
    let mut transposed = [0.0f32; 1024];
    transpose::<32, 32>(&tmp, &mut transposed);

    // Transform columns (now rows after transpose)
    for row in 0..32 {
        let row_start = row * 32;
        dct1d_32(&mut transposed[row_start..row_start + 32]);
        // Scale by 1/N
        for i in 0..32 {
            transposed[row_start + i] *= 1.0 / 32.0;
        }
    }

    // DO NOT transpose back! Same as DCT8x8/DCT16x16 - square blocks stay transposed.
    output.copy_from_slice(&transposed);
}

/// 4-point inverse DCT (type-III).
///
/// Direct formula implementation for the 4-point IDCT used in DC extraction.
/// Input: 4 frequency-domain coefficients, Output: 4 spatial-domain values.
fn idct1d_4(input: &[f32; 4], output: &mut [f32; 4]) {
    // The unnormalized type-III DCT of length 4:
    // X[k] = x[0] + sum_{n=1..3} x[n] * 2 * cos(pi * n * (2k+1) / 8) for k=0..3
    //
    // We use the butterfly decomposition matching libjxl's ComputeScaledIDCT:
    // Stage 1: B-transform (reverse of forward B-transform)
    // Stage 2: EvenOdd separation
    // Stage 3: WC multiply
    // Stage 4: IDCT on halves
    // Stage 5: AddSubReverse

    // For 4-point: direct computation is clearest.
    // cos(pi/8) = cos(22.5°), cos(3pi/8) = cos(67.5°)
    let c1 = core::f32::consts::FRAC_PI_8.cos(); // cos(pi/8) ≈ 0.9239
    let c3 = (3.0 * core::f32::consts::FRAC_PI_8).cos(); // cos(3pi/8) ≈ 0.3827

    let x0 = input[0];
    let x1 = input[1];
    let x2 = input[2];
    let x3 = input[3];

    // IDCT-III formula: out[k] = x[0] + 2 * sum_{n=1..N-1} x[n] * cos(pi*n*(2k+1)/(2N))
    // For N=4:
    output[0] = x0
        + 2.0
            * (x1 * (core::f32::consts::PI * 1.0 / 8.0).cos()
                + x2 * (core::f32::consts::PI * 2.0 / 8.0).cos()
                + x3 * (core::f32::consts::PI * 3.0 / 8.0).cos());
    output[1] = x0
        + 2.0
            * (x1 * (core::f32::consts::PI * 3.0 / 8.0).cos()
                + x2 * (core::f32::consts::PI * 6.0 / 8.0).cos()
                + x3 * (core::f32::consts::PI * 9.0 / 8.0).cos());
    output[2] = x0
        + 2.0
            * (x1 * (core::f32::consts::PI * 5.0 / 8.0).cos()
                + x2 * (core::f32::consts::PI * 10.0 / 8.0).cos()
                + x3 * (core::f32::consts::PI * 15.0 / 8.0).cos());
    output[3] = x0
        + 2.0
            * (x1 * (core::f32::consts::PI * 7.0 / 8.0).cos()
                + x2 * (core::f32::consts::PI * 14.0 / 8.0).cos()
                + x3 * (core::f32::consts::PI * 21.0 / 8.0).cos());

    // Suppress unused variable warning
    let _ = (c1, c3);
}

/// Extract DC values from 32x32 DCT coefficients.
/// Returns 16 DC values (for the 16 covered 8x8 blocks) in row-major 4x4 order.
///
/// The LLF region is 4x4 coefficients at positions `[r*32+c]` for r,c in 0..4
/// in the 32x32 layout (stride 32). We apply `DCTTotalResampleScale<32, 4>` to
/// each dimension, then a 4x4 IDCT to get the 16 DC values.
///
/// C++ uses `ReinterpretingIDCT<32, 32, 4, 4, 4, 4>` with the ROWS >= COLS branch
/// (since ROWS=COLS=4).
pub fn dc_from_dct_32x32(coeffs: &[f32; 1024]) -> [f32; 16] {
    // Step 1: Extract 4x4 LLF and apply resample scales
    let mut block = [0.0f32; 16];
    for iy in 0..4 {
        for ix in 0..4 {
            block[iy * 4 + ix] = coeffs[iy * 32 + ix]
                * DCT_RESAMPLE_SCALE_32_TO_4[iy]
                * DCT_RESAMPLE_SCALE_32_TO_4[ix];
        }
    }

    // Step 2: 4x4 IDCT via row-wise then column-wise 4-point IDCT
    // Row-wise
    let mut after_rows = [0.0f32; 16];
    for iy in 0..4 {
        let row_in: [f32; 4] = [
            block[iy * 4],
            block[iy * 4 + 1],
            block[iy * 4 + 2],
            block[iy * 4 + 3],
        ];
        let mut row_out = [0.0f32; 4];
        idct1d_4(&row_in, &mut row_out);
        for ix in 0..4 {
            after_rows[iy * 4 + ix] = row_out[ix];
        }
    }

    // Column-wise
    let mut result = [0.0f32; 16];
    for ix in 0..4 {
        let col_in: [f32; 4] = [
            after_rows[ix],
            after_rows[4 + ix],
            after_rows[8 + ix],
            after_rows[12 + ix],
        ];
        let mut col_out = [0.0f32; 4];
        idct1d_4(&col_in, &mut col_out);
        for iy in 0..4 {
            result[iy * 4 + ix] = col_out[iy];
        }
    }

    result
}

