//! Per-distance × per-display CVVDP JOD calibration table
//! (cvvdp-fork Phase 4 + Phase 2 display-config backfill).
//!
//! Phase 4 (2026-05-24) shipped the single-display SDR-200 table
//! (`vardct/cvvdp_targets.rs` initial commit — see
//! `docs/RFC_CVVDP_FORK.md` §2.1, §4 Phase 4 and
//! `docs/archive/RFC_CVVDP_PHASE4_BRIEF.md` Step 3).
//!
//! Phase 1 display-config backfill (2026-05-25, RFC
//! `docs/RFC_DISPLAY_CONFIG_BACKFILL.md`) extended the lookup to a
//! 3-row × 7-distance table covering [`crate::api::DisplayConfig`]'s
//! three Phase 1 variants. Phase 1 shipped heuristic seeds for Phone +
//! Tv (`WebSdr80 × {1.04, 1.12}`) gated on the upstream `CvvdpOpaque::new`
//! API which only accepted `DisplayModel` (not `DisplayGeometry`).
//!
//! **Phase 2 (2026-05-26)** lands the measured per-display tables:
//!
//! - [`crate::api::DisplayConfig::WebSdr80`] — preserved bit-identical
//!   from the Phase 4 seed (the legacy single-table values). Maps to
//!   `cvvdp_gpu::params::DisplayModel::STANDARD_4K` (200 cd/m² sRGB
//!   BT.709 at 250 lux ambient) + `DisplayGeometry::STANDARD_4K`
//!   (PPD ≈ 75.4).
//! - [`crate::api::DisplayConfig::Phone`] — 1000 cd/m² sustained-EDR
//!   sRGB Display-P3 at 200 lux indoor bright. Maps to a custom
//!   `DisplayModel` (built inline in [`crate::api::DisplayConfig::display_model`])
//!   + `DisplayGeometry::from_inches(2868, 1320, 11.8, 6.9)` (PPD ≈ 95).
//! - [`crate::api::DisplayConfig::Tv`] — `LG_OLED_2026_HDR_PQ` (3000
//!   cd/m² PQ BT.2020 at 5 lux dim) + `DisplayGeometry::LG_OLED_2026`.
//!
//! ## Purpose
//!
//! When the buttloop runs with the [GPU CVVDP backend] active, the
//! per-iter compare returns `score = (10.0 - JOD).clamp(0.0, 10.0)`
//! (mapped from cvvdp-gpu's native JOD ∈ [0, 10] where 10 = identical).
//! The buttloop's pre-existing convergence machinery consumes a
//! `target_distance` in butteraugli units (smaller = better, ~ [0, 5]
//! typical band). To keep the comparison surface coherent across
//! backends, when cvvdp is active the loop substitutes a
//! **cvvdp-native target** (in `score = 10 - JOD` space) interpolated
//! from this table at the caller-requested butteraugli `target_distance`
//! AND at the caller-requested [`crate::api::DisplayConfig`].
//!
//! [GPU CVVDP backend]: super::cvvdp_backend::gpu::GpuCvvdpBackend
//!
//! ## Phase 2 seed methodology — measured per-display tables
//!
//! Source: `benchmarks/cvvdp_per_display_reseed_2026-05-26.tsv` (3,402
//! rows: 1,134 unique cells × 3 displays). Generated by re-scoring
//! every (image, distance, effort) cell from Phase 1's tracking corpus
//! (`benchmarks/cvvdp_vs_buttloop_tracking_2026-05-24.tsv`, backend=B
//! rows) against the reference image under each of the three
//! `DisplayConfig`s. The CvvdpOpaque instance was constructed via
//! `CvvdpOpaque::new_with_geometry` (cvvdp_gpu master `a4994bb4`+) so
//! both the photometric AND geometric axes dispatch correctly per
//! display.
//!
//! Aggregation at `benchmarks/cvvdp_per_display_reseed_medians_2026-05-26.tsv`
//! collapses the n=162 scoring rows per (distance, display) into p25 /
//! p50 / p75 of `cvvdp_jod`. The per-distance medians are then
//! converted to butteraugli-direction `target = (10.0 - JOD_p50) × 1.05`
//! — the 1.05× tightening biases the cvvdp-driven loop to converge
//! slightly more strictly than what the butteraugli-driven baseline
//! achieves at the same nominal distance (matching Phase 4 methodology).
//!
//! ### Measured shifts vs Phase 1 heuristic
//!
//! Phase 1 modelled `Phone = WebSdr80 × 1.04` and `Tv = WebSdr80 × 1.12`
//! uniformly across distance. Measurement on the 1,134-cell corpus
//! shows the per-display Δ is STRONGLY distance-dependent — much
//! larger than the heuristic at low distance, smaller at high
//! distance (the Phone/Web ratio decreases from 2.91× at d=0.5 to
//! 1.06× at d=5.0; Tv/Web from 20.76× at d=0.5 to 1.79× at d=5.0).
//! A single global multiplier cannot capture this; Phase 2 ships
//! explicit per-distance arrays.
//!
//! Direction confirms the heuristic: `Tv > Phone > WebSdr80` at every
//! distance band. Magnitudes do not. The previously-documented per-row
//! 4% / 12% deltas are obsolete (left in `docs/RFC_DISPLAY_CONFIG_BACKFILL.md`
//! §7 commentary only).
//!
//! ### WebSdr80 measurement vs Phase 4 legacy
//!
//! The Phase 2 sweep measured WebSdr80 medians within ~3% of the
//! Phase 4 legacy values (`0.0025 / 0.0217 / 0.0454 / 0.0717 / 0.1318
//! / 0.2105 / 0.2966` measured vs `0.0029 / 0.0238 / 0.0461 / 0.0724
//! / 0.1336 / 0.2149 / 0.3005` legacy). The variance is from
//! corpus-composition differences between the Phase 4 baseline
//! (single-pass on the tracking sweep with mixed effort counts +
//! butteraugli-default cells) and this Phase 2 re-score (162 rows ×
//! 7 distances, all backend=B). The WebSdr80 row below is PINNED at
//! the Phase 4 legacy values exactly to preserve the byte-identity
//! invariant of the pre-Phase-1 single-table path; the
//! `websdr80_byte_identical_to_legacy_wrapper` unit test enforces
//! this.
//!
//! ## Monotonicity invariants
//!
//! - Within each row (display): targets grow with distance (stricter
//!   distance ⇒ larger acceptable cvvdp score).
//! - At each distance: `Tv >= Phone >= WebSdr80` (more luminance ⇒
//!   stricter convergence requirement). Holds on every measured cell
//!   in Phase 2.
//!
//! Both invariants are pinned by unit tests in `tests` module below.
//!
//! ## Linear interpolation
//!
//! [`cvvdp_target_score_for_distance_and_display`] interpolates
//! linearly between adjacent table points (within a row) and clamps
//! outside the band (`[0.50, 5.00]`). The table is monotone (target
//! grows with distance) so interpolation is well-defined per row.

