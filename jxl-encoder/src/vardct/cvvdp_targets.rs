    /// Phase 2 honeypot: ensure the Phone + Tv tables stay in measured
    /// ranges per distance. If a future refit moves them outside these
    /// envelopes, the seed methodology section should be re-verified
    /// against the new sweep TSV.
    #[test]
    fn phase2_tables_in_measured_envelope() {
        // Phone targets should stay within ±40% of the Phase 2
        // measurement at every distance (allows for small refits but
        // catches accidental zeros / order-of-magnitude bugs).
        for (i, (got, base)) in PHONE_TARGETS_BY_DISTANCE
            .iter()
            .zip([0.0072_f32, 0.0370, 0.0623, 0.0962, 0.1539, 0.2344, 0.3146].iter())
            .enumerate()
        {
            let rel = (got - base).abs() / base;
            assert!(
                rel < 0.40,
                "PHONE_TARGETS_BY_DISTANCE[{i}] = {got} drifted >40% from Phase 2 measurement {base}; \
                 re-verify against benchmarks/cvvdp_per_display_reseed_*.tsv before shipping"
            );
        }
        for (i, (got, base)) in TV_TARGETS_BY_DISTANCE
            .iter()
            .zip([0.0517_f32, 0.1412, 0.2002, 0.2483, 0.3429, 0.4318, 0.5310].iter())
            .enumerate()
        {
            let rel = (got - base).abs() / base;
            assert!(
                rel < 0.40,
                "TV_TARGETS_BY_DISTANCE[{i}] = {got} drifted >40% from Phase 2 measurement {base}; \
                 re-verify against benchmarks/cvvdp_per_display_reseed_*.tsv before shipping"
            );
        }
        // Phone targets must all be strictly less than Tv targets at
        // the same index (per-distance Tv > Phone invariant).
        for i in 0..CVVDP_DISTANCE_BANDS {
            assert!(
                PHONE_TARGETS_BY_DISTANCE[i] < TV_TARGETS_BY_DISTANCE[i],
                "PHONE_TARGETS_BY_DISTANCE[{}]={} MUST be < TV_TARGETS_BY_DISTANCE[{}]={}",
                i,
                PHONE_TARGETS_BY_DISTANCE[i],
                i,
                TV_TARGETS_BY_DISTANCE[i]
            );
        }
        // Phone targets must all be strictly greater than the Phase 4
        // WebSdr80 legacy values at the same index.
        for i in 0..CVVDP_DISTANCE_BANDS {
            assert!(
                PHONE_TARGETS_BY_DISTANCE[i] > WEB_SDR_80_TARGETS_BY_DISTANCE[i],
                "PHONE_TARGETS_BY_DISTANCE[{}]={} MUST be > WEB_SDR_80_TARGETS_BY_DISTANCE[{}]={}",
                i,
                PHONE_TARGETS_BY_DISTANCE[i],
                i,
                WEB_SDR_80_TARGETS_BY_DISTANCE[i]
            );
        }
    }
