//! Internal writer defenses, distinct from the public admission matrix.
use super::*;
fn manual(points: Vec<SplinePoint>) -> Spline {
    let mut color_dct = [[0.0; 32]; 3];
    color_dct[1][0] = 0.03;
    let mut sigma_dct = [0.0; 32];
    sigma_dct[0] = 1.5;
    Spline {
        control_points: points,
        color_dct,
        sigma_dct,
    }
}
#[test]
fn malformed_spline_sections_preserve_the_existing_writer() {
    for shape in ["empty", "mismatched", "empty-points"] {
        let mut data = SplinesData::from_splines(
            vec![manual(vec![SplinePoint::new(3.0, 7.0)])],
            0,
            0.0,
            1.0,
            8,
            8,
        )
        .unwrap();
        match shape {
            "empty" => data.splines.clear(),
            "mismatched" => data.quantized.clear(),
            "empty-points" => data.splines[0].control_points.clear(),
            _ => unreachable!(),
        }
        let mut writer = BitWriter::new();
        writer.write(8, 0xa5).unwrap();
        assert!(encode_splines_section(&data, &mut writer).is_err());
        assert_eq!(writer.bits_written(), 8);
        assert_eq!(writer.as_bytes(), [0xa5]);
    }
}
#[test]
fn frame_writer_refuses_unimplemented_splines_before_writing() {
    use crate::headers::frame_header::FrameOptions;
    use crate::vardct::encoder::VarDctEncoder;
    for points in [
        vec![],
        vec![SplinePoint::new(3.0, 7.0), SplinePoint::new(6.0, 7.0)],
    ] {
        let mut encoder = VarDctEncoder::new(1.0);
        encoder.splines = Some(vec![manual(points)]);
        let mut writer = BitWriter::new();
        writer.write(8, 0xa5).unwrap();
        let result = encoder.encode_frame_to_writer(
            8,
            8,
            &[0.5; 8 * 8 * 3],
            &[],
            &FrameOptions::default(),
            &mut writer,
            None,
        );
        let error = result.unwrap_err();
        assert!(error.to_string().contains("spline"));
        assert_eq!(writer.bits_written(), 8);
        assert_eq!(writer.as_bytes(), [0xa5]);
    }
}

#[test]
fn numeric_boundaries_and_empty_section_are_checked() {
    for value in [
        f32::NAN,
        f32::INFINITY,
        f32::NEG_INFINITY,
        f32::MAX,
        f32::MIN,
        2_147_483_648.0,
        -2_147_483_904.0,
    ] {
        assert!(quantized_coefficient(value).is_err(), "{value}");
    }
    for value in [0.0, -1.0, 2_147_483_520.0, -2_147_483_648.0] {
        assert_eq!(quantized_coefficient(value).unwrap(), value.round() as i32);
    }
    assert!(rounded_coordinate(f32::MIN).is_err());
    assert_eq!(
        rounded_coordinate(-9_223_372_036_854_775_808.0).unwrap(),
        i64::MIN
    );
    assert!(SplinesData::from_splines(vec![], 0, 0.0, 1.0, 8, 8).is_err());
    for channel in 0..4 {
        let mut source = manual(vec![SplinePoint::new(3.0, 7.0)]);
        if channel == 3 {
            source.sigma_dct[0] = -1e10;
        } else {
            source.color_dct[channel][0] = 1e10;
        }
        assert!(SplinesData::from_splines(vec![source], 0, 0.0, 1.0, 8, 8).is_err());
    }
}

#[test]
fn valid_quantized_coefficients_match_unmodified_v012_object() {
    // Generated by scripts/spline_quantization_oracle.cc using native Create.
    for line in include_str!("spline_quantization_native.tsv").lines() {
        let fields: Vec<i64> = line.split('\t').map(|v| v.parse().unwrap()).collect();
        let mut source = manual(if fields[0] == 0 {
            vec![
                SplinePoint::new(3.49, 7.49),
                SplinePoint::new(3.51, 7.49),
                SplinePoint::new(6.0, 8.0),
            ]
        } else {
            vec![SplinePoint::new(20.0, 7.0)]
        });
        source.color_dct = [[0.0; 32]; 3];
        source.sigma_dct = [0.0; 32];
        source.color_dct[0][0] = 0.02;
        source.color_dct[0][2] = -0.04;
        source.color_dct[1][0] = 0.03;
        source.color_dct[1][1] = -0.05;
        source.color_dct[2][0] = -0.06;
        source.color_dct[2][3] = 0.08;
        source.sigma_dct[0] = 1.5;
        source.sigma_dct[2] = -0.2;
        validate_splines(&[source.clone()]).unwrap();
        let quantized =
            QuantizedSpline::from_spline(&source, fields[1] as i32, 0.03125, 1.125).unwrap();
        let mut actual = Vec::new();
        for (x, y) in quantized.control_points {
            actual.extend([x, y]);
        }
        actual.extend(quantized.color_dct.into_iter().flatten().map(i64::from));
        actual.extend(quantized.sigma_dct.into_iter().map(i64::from));
        assert_eq!(
            actual,
            fields[2..],
            "shape={} adjustment={}",
            fields[0],
            fields[1]
        );
    }
}

#[test]
fn each_coordinate_error_reaches_the_internal_constructor_and_still_entry() {
    for points in [
        vec![],
        vec![SplinePoint::new(3.0, f32::NAN)],
        vec![SplinePoint::new(3.0, 7.0), SplinePoint::new(f32::NAN, 8.0)],
        vec![SplinePoint::new(3.0, 7.0), SplinePoint::new(4.0, f32::NAN)],
    ] {
        assert!(
            SplinesData::from_splines(vec![manual(points.clone())], 0, 0.0, 1.0, 8, 8).is_err()
        );
        let mut encoder = crate::vardct::encoder::VarDctEncoder::new(1.0);
        encoder.splines = Some(vec![manual(points)]);
        assert!(encoder.encode(8, 8, &[0.5; 8 * 8 * 3], None).is_err());
    }
}

#[test]
fn automatic_trial_discards_unrepresentable_candidates() {
    let mut overflow = manual(vec![SplinePoint::new(0.0, 3.0), SplinePoint::new(7.0, 3.0)]);
    overflow.color_dct[0][0] = f32::MAX;
    for candidate in [
        manual(vec![]),
        manual(vec![SplinePoint::new(3.1, 7.1), SplinePoint::new(3.4, 7.4)]),
        overflow,
        // Valid candidate in a flat, empty image has no residual-energy gain.
        manual(vec![SplinePoint::new(0.0, 3.0), SplinePoint::new(7.0, 3.0)]),
    ] {
        assert!(!spline_passes_trial_encode_gate(
            &candidate, &[0.0; 64], &[0.0; 64], &[0.0; 64], 8, 8, 8, 1.0
        ));
    }
}
