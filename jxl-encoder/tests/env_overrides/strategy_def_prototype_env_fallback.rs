/// All four enum letters parse correctly through the env hook on
/// `Libjxl` (preset = `Off` = default).
#[test]
fn env_iter_mode_all_letters_parse() {
    let _env_serial = crate::env_serial();
    let (_guard, snapshot) = env_lock_and_snapshot();
    for (letter, expected) in [
        ("A", PrototypeIterMode::Off),
        ("B", PrototypeIterMode::SmoothSkip),
        ("C", PrototypeIterMode::TexturedExtend),
        ("D", PrototypeIterMode::Combined),
    ] {
        // SAFETY: env-var mutex is held.
        unsafe { std::env::set_var("JXL_W44_168_MODE", letter) };
        let (_, _, iters) = resolve_prototype_strategy_named_for_test("Libjxl");
        assert_eq!(
            iters, expected,
            "letter `{letter}` should parse to {expected:?} on Libjxl preset (default Off)",
        );
    }
    env_restore(snapshot);
}

/// Both env vars set simultaneously: each fires independently on its
/// own gate.
#[test]
fn env_both_vars_independent() {
    let _env_serial = crate::env_serial();
    let (_guard, snapshot) = env_lock_and_snapshot();
    // SAFETY: env-var mutex is held.
    unsafe { std::env::set_var("JXL_W44_184_FORCE_LIBJXL_NEWTON", "1") };
    // SAFETY: env-var mutex is held.
    unsafe { std::env::set_var("JXL_W44_168_MODE", "D") };
    // Zenjxl (cfl=false=default, iters=SmoothSkip≠default):
    //   cfl flips to true; iters stays SmoothSkip.
    let (cfl, _, iters) = resolve_prototype_strategy_named_for_test("Zenjxl");
    assert!(cfl);
    assert_eq!(iters, PrototypeIterMode::SmoothSkip);
    // Libjxl (cfl=true≠default, iters=Off=default):
    //   cfl stays true; iters promotes to Combined.
    let (cfl, _, iters) = resolve_prototype_strategy_named_for_test("Libjxl");
    assert!(cfl);
    assert_eq!(iters, PrototypeIterMode::Combined);
    env_restore(snapshot);
}
