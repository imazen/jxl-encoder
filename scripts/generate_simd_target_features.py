#!/usr/bin/env python3
"""Generate additive array/slice wrappers for the legacy exported SIMD kernels."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'jxl-encoder-simd/src'
lib = (root / 'lib.rs').read_text()
# Keep this inventory explicit: it is the pre-migration set of concrete exports.
inventory = root / 'legacy_exports.rs'
if not inventory.exists():
    start = lib.index('// --- AVX2 variants')
    inventory.write_text(lib[start:])
    (root / 'lib.rs').write_text(lib[:start] + 'mod legacy;\npub use legacy::*;\n\npub mod target_features;\n')


def split_args(s):
    result, start, depth = [], 0, 0
    for i, c in enumerate(s):
        if c in '([<': depth += 1
        if c in ')]>': depth -= 1
        if c == ',' and depth == 0:
            result.append(s[start:i].strip()); start = i + 1
    if s[start:].strip(): result.append(s[start:].strip())
    return result


def resolve(module, name):
    source = (root / (module + '.rs')).read_text()
    direct = re.search(r'pub fn ' + re.escape(name) + r'\s*\((.*?)\)\s*(->[^\{]+)?\{', source, re.S)
    if direct:
        return direct, source, name
    alias = re.search(r'pub use (\w+) as ' + re.escape(name) + r';', source)
    if alias: return resolve(module, alias[1])
    base = re.sub(r'_(v3|v4|neon|wasm128)$', '', name)
    if base != name:
        return resolve(module, base)
    raise RuntimeError((module, name))

header = '// Generated by scripts/generate_simd_target_features.py from legacy_exports.rs and kernel signatures.\n'
imports = '#[cfg(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "wasm32"))]\nuse crate::{EntropyCoeffResult, XybCubeRoot};\n#[cfg(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "wasm32"))]\nuse alloc::vec::Vec;\n\n'
legacy = header + '//! Compatibility entry points with the original token signatures.\n\n' + imports
modern = header + '''//! Array and slice kernels for callers with statically enabled CPU features.
//!
//! Each function calls the same implementation as its legacy token-taking counterpart.
//! No runtime detection occurs. Features must appear on the **calling function's**
//! `#[target_feature]` attribute (or an equivalent `#[archmage::rite]` attribute).
//! A native baseline safe caller gets E0133; use the crate-root runtime-dispatched function
//! there. Do not add an unsafe block to bypass that diagnostic.
//!
//! Required feature sets (in addition to each architecture's baseline):
//! - `_v3`: sse, sse2, sse3, ssse3, sse4.1, sse4.2, popcnt, cmpxchg16b,
//!   avx, avx2, fma, bmi1, bmi2, f16c, lzcnt, movbe.
//! - `_v4` (Cargo `avx512`): all v3 features plus pclmulqdq, aes, avx512f, avx512bw,
//!   avx512cd, avx512dq, avx512vl.
//! - `_neon`: neon. `_wasm128`: simd128.
//!
//! Layout, stride, bounds and numerical behavior are inherited from the linked
//! legacy entry point. A tier's output need not equal a different tier's output.
//! On wasm32, Rust permits safe calls from baseline functions as well: the
//! engine validates module CPU features at load time. This is an exception to
//! the native E0133 rule. These functions still require an engine with SIMD128.
//! No speed or inlining guarantee is made.
//!

#![cfg_attr(target_arch = "x86_64", doc = r#"
Safe composition uses only arrays at the boundary:

```
#[target_feature(enable = "sse,sse2,sse3,ssse3,sse4.1,sse4.2,popcnt,cmpxchg16b,avx,avx2,fma,bmi1,bmi2,f16c,lzcnt,movbe")]
fn transform(input: &[f32; 64], output: &mut [f32; 64]) {
    let mut coefficients = [0.0; 64];
    jxl_encoder_simd::target_features::dct_8x8_v3(input, &mut coefficients);
    jxl_encoder_simd::target_features::idct_8x8_v3(&coefficients, output);
}
```

```compile_fail,E0133
fn baseline() {
    let mut output = [0.0; 64];
    jxl_encoder_simd::target_features::dct_8x8_v3(&[0.0; 64], &mut output);
}
```
"#)]
#![cfg_attr(target_arch = "aarch64", doc = r#"
```compile_fail,E0133
fn baseline() {
    let mut output = [0.0; 64];
    jxl_encoder_simd::target_features::dct_8x8_neon(&[0.0; 64], &mut output);
}
```
"#)]
#![cfg_attr(target_arch = "wasm32", doc = r#"
WASM baseline calls are safe; the engine validates SIMD128 when loading the module.

```
fn baseline() {
    let mut output = [0.0; 64];
    jxl_encoder_simd::target_features::dct_8x8_wasm128(&[0.0; 64], &mut output);
}
```
"#)]

''' + imports
counts = {}
for block in re.finditer(r'#\[cfg\(target_arch = "(\w+)"\)\]\s*pub use (\w+)::(\{.*?\}|\w+(?: as \w+)?);', inventory.read_text(), re.S):
    arch, module, items = block.groups()
    tier, token = {'x86_64': ('v3', 'X64V3Token'), 'aarch64': ('neon', 'NeonToken'), 'wasm32': ('wasm128', 'Wasm128Token')}[arch]
    for item in items.strip('{}').split(','):
        if not item.strip(): continue
        names = re.split(r'\s+as\s+', item.strip())
        original, public = names[0], names[-1]
        match, source, base = resolve(module, original)
        args = split_args(match[1])
        assert 'Token' in args[0], (module, original, args)
        plain = args[1:]
        arguments = ', '.join(x.split(':', 1)[0].strip().removeprefix('mut ') for x in plain)
        signature = ', '.join(plain).replace('NUM_NOISE_POINTS', '8')
        result = (match[2] or '').strip()
        new = re.sub(r'_avx2$', '_v3', public)
        cfg = f'#[cfg(target_arch = "{arch}")]\n'
        legacy += cfg + f'#[deprecated(note = "Use target_features::{new} inside a matching target-feature function, or the runtime-dispatched entry point.")]\n#[inline]\npub fn {public}(token: archmage::{token}, {signature}) {result} {{\n    crate::{module}::{original}(token, {arguments})\n}}\n\n'
        modern += cfg + f'/// Token-free counterpart of [`crate::{public}`].\n#[archmage::rite({tier})]\npub fn {new}({signature}) {result} {{\n    crate::{module}::{original}(archmage::{token}::from_context(), {arguments})\n}}\n\n'
        counts[tier] = counts.get(tier, 0) + 1
        # Expose existing generated AVX-512 implementations, without adding kernels.
        preceding = source[:match.start()]
        attrs = preceding[preceding.rfind('#[magetypes'):]
        if tier == 'v3' and '#[magetypes' in attrs and re.search(r'\bv4\b', attrs) and '}' not in attrs:
            modern += '#[cfg(all(target_arch = "x86_64", feature = "avx512"))]\n' + f'/// AVX-512 counterpart of [`{new}`], using the existing v4 kernel.\n#[archmage::rite(v4)]\npub fn {new[:-2]}v4({signature}) {result} {{\n    crate::{module}::{base}_v4(archmage::X64V4Token::from_context(), {arguments})\n}}\n\n'
            counts['v4'] = counts.get('v4', 0) + 1
(root / 'legacy.rs').write_text(legacy)
(root / 'target_features.rs').write_text(modern)
print(counts)

import subprocess
subprocess.run(["rustfmt", "--edition", "2024", str(root/"legacy.rs"), str(root/"target_features.rs")], check=True)
