#!/usr/bin/env python3
"""Generate boundary parity cases for every token-free kernel and its old entry."""
import re
from pathlib import Path
from generate_simd_target_features import split_args

root = Path(__file__).resolve().parents[1]
src = root / 'jxl-encoder-simd/src'
tests = root / 'jxl-encoder-simd/tests'
tests.mkdir(exist_ok=True)
text = '''// Generated by scripts/generate_simd_api_parity.py.
// Tests boundary argument forwarding and float bits, against the existing tier.
#![forbid(unsafe_code)]
#![cfg(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "wasm32"))]
#![allow(clippy::too_many_arguments)]
use jxl_encoder_simd::{self as legacy, target_features as feature};

fn data<const N: usize>(seed: usize) -> [f32; N] {
    core::array::from_fn(|i| ((i * 17 + seed * 13) % 97) as f32 * 0.03125 - 1.0)
}
fn bits(v: &[f32]) -> Vec<u32> { v.iter().map(|v| v.to_bits()).collect() }
fn entropy_bits(v: legacy::EntropyCoeffResult) -> [u32; 4] {
    [v.entropy_sum.to_bits(), v.info_loss2_sum.to_bits(), v.info_loss_sum.to_bits(), v.nzeros_sum.to_bits()]
}
'''
values = dict(width='width',height='width',stride='width',plane_stride='width',in_stride='width + 6',pad='3',xsize_blocks='2',ysize_blocks='2',padded_width='width',nblocks='4',num='width',n='width',tile_x0='0',tile_y0='0',tile_x1='width',tile_y1='width',rect_x0_blocks='0',rect_y0_blocks='0',rect_w_blocks='2',rect_h_blocks='2',aq_map_stride='2',grid_width='2',grid_height='2',llf_x='1',llf_y='1',bx='0',by='0',mask_row_base='0',mask_stride='width',block_width='8',block_height='8',total_count='10240')
legacy_names = set(re.findall(r'pub fn (\w+)\(', (src/'legacy.rs').read_text()))
v4text = text.replace('use jxl_encoder_simd::{self as legacy, target_features as feature};', 'extern crate std;\nuse alloc::vec::Vec;\nuse crate::{self as legacy, target_features as feature};')
count = 0
v4count = 0
for m in re.finditer(r'#\[cfg\(([^\]]+)\)\]\s*///[^\n]*\n#\[archmage::rite\((\w+)\)\]\s*pub fn (\w+)\((.*?)\)\s*(->[^\{]+)?\{', (src/'target_features.rs').read_text(), re.S):
    cfg,tier,name,args,result = m.groups()
    old = name[:-3]+'_avx2' if tier=='v3' else name
    # V4 has no root legacy export; its unit tests compare the existing private kernel.
    if old not in legacy_names and tier != 'v4': continue
    token = dict(v3='X64V3Token',neon='NeonToken',wasm128='Wasm128Token',v4='X64V4Token')[tier]
    setup=[];newargs=[];oldargs=[];checks=[]
    for arg in split_args(args):
        param,ty=arg.split(':',1);param=param.strip();ty=ty.strip()
        if ty=='usize':
            val=values[param];newargs.append(val);oldargs.append(val)
        elif ty=='f32':newargs.append('0.75');oldargs.append('0.75')
        elif ty=='bool':newargs.append('seed % 2 == 0');oldargs.append('seed % 2 == 0')
        elif ty=='XybCubeRoot':newargs.append('legacy::XybCubeRoot::Libjxl');oldargs.append('legacy::XybCubeRoot::Libjxl')
        elif ty=='[f32; 3]':newargs.append('[0.5, 0.75, 1.0]');oldargs.append('[0.5, 0.75, 1.0]')
        elif ty=='[&[f32]; 3]':
            setup.append(f'let {param} = data::<4096>(seed + {1 if param=="original" else 2});')
            newargs.append(f'[&{param}; 3]');oldargs.append(f'[&{param}; 3]')
        elif ty=='Option<&mut [f32; 64]>':
            setup.append(f'let mut {param}_new = [0.0; 64]; let mut {param}_old = [0.0; 64];')
            newargs.append(f'Some(&mut {param}_new)');oldargs.append(f'Some(&mut {param}_old)');checks.append(f'assert_eq!(bits(&{param}_new), bits(&{param}_old));')
        else:
            array=re.search(r'\[(f32|i32); (\d+)\]',ty)
            kind=array[1] if array else ('i32' if '[i32]' in ty else 'f32')
            size=array[2] if array else '4096'
            # Positive weights keep all quantization/entropy domains meaningful.
            init=(f'[1_i32; {size}]' if kind=='i32' else f'data::<{size}>(seed)')
            if any(x in param for x in ['weight','sigma','lut']):init=f'[1.25_f32; {size}]'
            if '&mut' in ty:
                setup.append(f'let mut {param}_new = {init}; let mut {param}_old = {param}_new;')
                newargs.append(f'&mut {param}_new');oldargs.append(f'&mut {param}_old')
                checks.append(f'assert_eq!({"bits(&"+param+"_new)" if kind=="f32" else param+"_new"}, {"bits(&"+param+"_old)" if kind=="f32" else param+"_old"});')
            else:
                setup.append(f'let {param} = {init};');newargs.append('&'+param);oldargs.append('&'+param)
    result=(result or '').strip()
    if 'EntropyCoeffResult' in result: check='assert_eq!(entropy_bits(actual), entropy_bits(expected));'
    elif 'Vec<f32>, usize, usize' in result:check='assert_eq!((bits(&actual.0), actual.1, actual.2), (bits(&expected.0), expected.1, expected.2));'
    elif 'Vec<f32>' in result:check='assert_eq!(bits(&actual), bits(&expected));'
    elif result in ('-> f32','-> f64'):check='assert_eq!(actual.to_bits(), expected.to_bits());'
    elif result:check='assert_eq!(actual, expected);'
    else:check=''
    binding = 'let actual = ' if result else ''
    oldbinding = 'let expected = ' if result else ''
    if tier == 'v4':
        body = (src/'target_features.rs').read_text()[m.end():]
        oldcall = re.search(r'crate::(\w+::\w+)\(', body)[1]
        oldcall = 'crate::' + oldcall
    else:
        oldcall = 'legacy::' + old
    case=f'''\n#[cfg({cfg})]
#[test]
fn {name}_matches_legacy() {{
    use archmage::SimdToken;
    let _guard = archmage::testing::lock_token_testing();
    #[archmage::arcane]
    #[allow(deprecated)] // This test deliberately exercises the compatibility API.
    fn run(token: archmage::{token}) {{
        for (seed, width) in [(0, 16), (1, 17), (2, 32)] {{
            let _ = (seed, width);
            {' '.join(setup)}
            {binding}feature::{name}({', '.join(newargs)});
            {oldbinding}{oldcall}(token, {', '.join(oldargs)});
            {check}
            {' '.join(checks)}
        }}
    }}
    if let Some(token) = archmage::{token}::summon() {{ run(token); }}
    else {{ assert_ne!(std::env::var("JXL_REQUIRE_TOKEN").as_deref(), Ok("{token}"), "required SIMD tier unavailable"); }}
}}
'''
    if tier == 'v4': v4text += case; v4count += 1
    else: text += case; count += 1
text += """
#[cfg(target_arch = "wasm32")]
#[test]
fn wasm_baseline_safe_composition() {
    let input = data::<64>(9);
    let mut coefficients = [0.0; 64];
    let mut output = [0.0; 64];
    // These calls intentionally have no target_feature attribute or token.
    feature::dct_8x8_wasm128(&input, &mut coefficients);
    feature::idct_8x8_wasm128(&coefficients, &mut output);
    assert!(output.iter().all(|value| value.is_finite()));
}
"""
(tests/'target_features_parity.rs').write_text(text)
(src/'target_features_v4_tests.rs').write_text(v4text)
print('parity entry points:',count, '+', v4count, 'v4')

import subprocess
subprocess.run(["rustfmt", "--edition", "2024", str(tests/"target_features_parity.rs"), str(src/"target_features_v4_tests.rs")], check=True)
